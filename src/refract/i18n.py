from __future__ import annotations

from typing import Literal

Language = Literal["ru", "en"]
LANGUAGES: tuple[Language, ...] = ("ru", "en")
DEFAULT_LANGUAGE: Language = "ru"


def norm_lang(lang: str | None) -> Language:
    """'EN', 'en-US', 'english' → 'en'; unknown or empty → the default language."""
    key = (lang or "").strip().lower()[:2]
    if key == "en":  # "en", "en-US", "english"
        return "en"
    if key in ("ru", "ру"):  # "ru", "ru-RU", "russian", "русский"
        return "ru"
    return DEFAULT_LANGUAGE


